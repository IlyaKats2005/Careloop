import { mkdir, writeFile, readFile, copyFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { buildBls12381 } from 'ffjavascript';
import { powersOfTau, zKey } from 'snarkjs';
await mkdir('zk/build',{recursive:true}); await mkdir('public/zk',{recursive:true});
execFileSync('node',['node_modules/circom2/cli.js','zk/reward.circom','--r1cs','--wasm','--sym','--O2','--prime','bls12381','-o','zk/build'],{stdio:'inherit'});
const curve=await buildBls12381(true);
console.log('Creating development-only BLS12-381 ceremony (power 12).');
await powersOfTau.newAccumulator(curve,12,'zk/build/0.ptau');
await powersOfTau.contribute('zk/build/0.ptau','zk/build/1.ptau','Careloop DEMO ONLY',randomBytes(64).toString('hex'));
console.log('Preparing phase 2…');
await powersOfTau.preparePhase2('zk/build/1.ptau','zk/build/final.ptau');
await zKey.newZKey('zk/build/reward.r1cs','zk/build/final.ptau','zk/build/0.zkey',console);
await zKey.contribute('zk/build/0.zkey','public/zk/reward.zkey','Careloop DEMO ONLY',randomBytes(64).toString('hex'));
const vk=await zKey.exportVerificationKey('public/zk/reward.zkey');
await writeFile('public/zk/verification_key.json',JSON.stringify(vk));
await copyFile('zk/build/reward_js/reward.wasm','public/zk/reward.wasm');
console.log('Development artifacts ready. NOT a production MPC ceremony.');
await curve.terminate(); process.exit(0);
